#!/usr/bin/env bash
#
# BUFFALO continuous integration checks.
#
# All CI logic lives here so it can move between CI systems unchanged. The
# script expects PHP 8.4 (with the extensions from docker/php/Dockerfile),
# Composer, Node.js and npm on PATH, and reachable PostgreSQL/PostGIS and
# Valkey services (DB_HOST / REDIS_HOST etc. from the environment or .env).
#
# Locally, run `make ci`: it runs this script in the `ci` Docker image against
# a clean copy of the working tree.
#
# Stops at the first failing step.

set -euo pipefail

cd "$(dirname "$0")/.."

step() {
    printf '\n\033[1;34m==> %s\033[0m\n' "$1"
}

if [[ ! -f .env ]]; then
    cp .env.example .env
fi

step "Composer install"
composer install --no-interaction --no-progress --prefer-dist

if ! grep -Eq '^APP_KEY=.+' .env; then
    php artisan key:generate --no-interaction
fi

if ! grep -Eq '^CIPHERSWEET_KEY=.+' .env; then
    php artisan buffalo:encryption-key --no-interaction
fi

step "npm install"
npm ci --no-audit --no-fund

step "Frontend build"
npm run build

step "Pint (test mode)"
vendor/bin/pint --test

step "Larastan"
vendor/bin/phpstan analyse --no-progress --memory-limit=1G

step "ESLint"
npm run lint

step "Prettier check"
npm run format:check

step "TypeScript typecheck"
npm run typecheck

step "Vitest"
# Uses the Wayfinder helpers generated by the frontend build.
npm run test

step "Prepare test database"
# CI service containers cannot run docker/postgres/init, so make sure the
# test database, its extensions and the database roles exist (idempotent).
# This step connects as the superuser (DB_ADMIN_*); the tests themselves run
# as buffalo_app and migrate as buffalo_owner (Phase 8A).
php <<'PHP'
<?php
require 'vendor/autoload.php';
$env = Dotenv\Dotenv::createImmutable(getcwd());
$env->safeLoad();
$get = fn (string $key, string $default) => $_SERVER[$key] ?? $_ENV[$key] ?? getenv($key) ?: $default;
$dsn = sprintf('pgsql:host=%s;port=%s', $get('DB_HOST', '127.0.0.1'), $get('DB_PORT', '5432'));
$user = $get('DB_ADMIN_USERNAME', 'buffalo');
$password = $get('DB_ADMIN_PASSWORD', 'buffalo');

$pdo = new PDO($dsn.';dbname=postgres', $user, $password, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
if (! $pdo->query("SELECT 1 FROM pg_database WHERE datname = 'buffalo_test'")->fetchColumn()) {
    $pdo->exec('CREATE DATABASE buffalo_test');
}
$test = new PDO($dsn.';dbname=buffalo_test', $user, $password, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
foreach (['postgis', 'pg_trgm', 'unaccent'] as $extension) {
    $test->exec("CREATE EXTENSION IF NOT EXISTS {$extension}");
}
echo "buffalo_test ready\n";
PHP
php artisan buffalo:db:provision-roles --database=buffalo_test --no-interaction

step "Secrets check (production-like)"
# Phase 8A: development defaults must be refused; real secrets supplied as
# files (as Docker secrets are) must pass. Prints names only.
if APP_ENV=production php artisan buffalo:secrets:check --no-interaction >/dev/null 2>&1; then
    echo "buffalo:secrets:check accepted development defaults" >&2
    exit 1
fi
secrets_dir=$(mktemp -d)
trap 'rm -rf "$secrets_dir"' EXIT
printf 'base64:%s' "$(head -c 32 /dev/urandom | base64)" > "$secrets_dir/app_key"
head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n' > "$secrets_dir/ciphersweet_key"
for name in db_password redis_password reverb_app_key reverb_app_secret; do
    head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n' > "$secrets_dir/$name"
done
APP_ENV=production MAIL_USERNAME= DB_MIGRATIONS_PASSWORD= DB_READONLY_PASSWORD= \
    APP_KEY_FILE="$secrets_dir/app_key" CIPHERSWEET_KEY_FILE="$secrets_dir/ciphersweet_key" \
    DB_PASSWORD_FILE="$secrets_dir/db_password" REDIS_PASSWORD_FILE="$secrets_dir/redis_password" \
    REVERB_APP_KEY_FILE="$secrets_dir/reverb_app_key" REVERB_APP_SECRET_FILE="$secrets_dir/reverb_app_secret" \
    php artisan buffalo:secrets:check --no-interaction

step "Pest"
php artisan config:clear --no-interaction
php artisan test

printf '\n\033[1;32mAll CI checks passed.\033[0m\n'
