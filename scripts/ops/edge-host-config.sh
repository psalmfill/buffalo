#!/bin/sh
#
# edge-host-config.sh [--config FILE]: prints a server block for the HOST's
# nginx, for edge mode proxy (BUFFALO behind an existing nginx on a shared
# server). Save it as /etc/nginx/sites-available/buffalo, link it into
# sites-enabled, replace the two certificate placeholders, then
# `nginx -t && systemctl reload nginx`.
#
#   --config FILE   the settings file (default: .uat/buffalo.env when run
#                   from a source tree with a UAT environment, otherwise
#                   /etc/buffalo/buffalo.env)
#
# The host name comes from DEMO_HOST (UAT) or BUFFALO_SERVER_NAME
# (production); the port from BUFFALO_EDGE_PORT (default 8090). Prints
# settings only, never secrets. `make edge-host-config` runs it.
set -eu

config=""
while [ $# -gt 0 ]; do
    case "$1" in
        --config) config=$2; shift 2 ;;
        -h|--help) sed -n '2,/^set -eu/p' "$0" | sed '$d; s/^# \{0,1\}//'; exit 0 ;;
        *) echo "Unknown option: $1 (see --help)" >&2; exit 1 ;;
    esac
done
if [ -z "$config" ]; then
    if [ -f .uat/buffalo.env ]; then config=.uat/buffalo.env; else config=/etc/buffalo/buffalo.env; fi
fi
[ -r "$config" ] || { echo "Cannot read $config (pass --config FILE)." >&2; exit 1; }

setting() { sed -n "s/^$1=//p" "$config" | tail -n 1 | tr -d '"'; }
mode=$(setting BUFFALO_EDGE)
[ "$mode" = proxy ] || { echo "$config is not in edge mode proxy (BUFFALO_EDGE=${mode:-direct}): the host's nginx is not used. See docs/operations/installation.md, \"Edge modes\"." >&2; exit 1; }
host=$(setting DEMO_HOST)
[ -n "$host" ] || host=$(setting BUFFALO_SERVER_NAME)
[ -n "$host" ] || { echo "No host name in $config (DEMO_HOST or BUFFALO_SERVER_NAME)." >&2; exit 1; }
port=$(setting BUFFALO_EDGE_PORT)
port=${port:-8090}
name=$(printf '%s' "$host" | tr -c 'A-Za-z0-9.-' '-')

cat <<NGINX
# BUFFALO behind this server's nginx (edge mode proxy), for $host.
# Generated by edge-host-config.sh from $config.
#
# Install:
#   sudo tee /etc/nginx/sites-available/buffalo-$name >/dev/null   (paste this)
#   sudo ln -s /etc/nginx/sites-available/buffalo-$name /etc/nginx/sites-enabled/
#   Replace the two CHANGE-ME certificate paths below, then:
#   sudo nginx -t && sudo systemctl reload nginx
#
# BUFFALO listens on http://127.0.0.1:$port only and trusts X-Forwarded-For
# and X-Forwarded-Proto from Docker's gateway (connections from this nginx
# to the published port arrive from it). This block sets both, overwriting
# anything the browser sent.

# Remove this map if your nginx configuration already defines
# \$connection_upgrade (for example in another site).
map \$http_upgrade \$connection_upgrade {
    default upgrade;
    ''      close;
}

server {
    listen 80;
    listen [::]:80;
    server_name $host;
    return 301 https://\$host\$request_uri;
}

server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name $host;

    # CHANGE-ME: the certificate for $host (for example from certbot on
    # this host: /etc/letsencrypt/live/$host/fullchain.pem and privkey.pem).
    ssl_certificate     /etc/ssl/CHANGE-ME/$host/fullchain.pem;
    ssl_certificate_key /etc/ssl/CHANGE-ME/$host/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;

    # Evidence uploads (keep in step with BUFFALO's 100 MB limit).
    client_max_body_size 100M;

    location / {
        proxy_pass http://127.0.0.1:$port;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        # The browser's address, replacing (not appending to) any header the
        # browser sent: BUFFALO records it in the login history.
        proxy_set_header X-Forwarded-For \$remote_addr;
        proxy_set_header X-Forwarded-Proto https;
        # WebSockets (live notifications, wss://$host/app/...) on the same
        # host and port.
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection \$connection_upgrade;
        proxy_read_timeout 120s;
        proxy_buffering off;
        # BUFFALO's response headers (security policy, cookies) exceed
        # nginx's default 4-8 KB header buffer: without these, 502.
        proxy_buffer_size 32k;
        proxy_buffers 8 32k;
        proxy_busy_buffers_size 64k;
    }
}
NGINX
